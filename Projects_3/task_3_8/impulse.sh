#!/bin/bash

# Проверяем, что передано хотя бы два аргумента
if [ $# -lt 2 ]; then
    echo "Ошибка: недостаточно аргументов."
    echo "Использование: $0 <имя гена> <уровень экспрессии>"
    exit 1
fi

GENE_NAME=$1
EXPRESSION_LEVEL=$2

# Дополнительно можно проверить, что второй аргумент — целое число
# (необязательно, но улучшает надёжность)
if ! [[ "$EXPRESSION_LEVEL" =~ ^-?[0-9]+$ ]]; then
    echo "Ошибка: уровень экспрессии должен быть целым числом."
    exit 1
fi

echo "Экспрессия гена $GENE_NAME составляет $EXPRESSION_LEVEL единиц"
