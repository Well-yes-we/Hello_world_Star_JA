#!/bin/bash

# Перебор чисел от 1 до 20
for i in {1..20}; do
    # Если число равно 15, прерываем цикл
    if [ $i -eq 15 ]; then
        echo "Достигнуто число 15. Остановка."
        break
    fi

    # Если число чётное, пропускаем вывод
    if [ $((i % 2)) -eq 0 ]; then
        continue
    fi

    # Выводим нечётное число
    echo $i
done

