#!/bin/bash

# Функция проверки прав root
check_root() {
    if [ "$EUID" -ne 0 ]; then
        echo "Ошибка: этот скрипт должен быть запущен от имени суперпользователя (root)." >&2
        exit 1
    fi
}

# Вызов функции
check_root

# Остальной код скрипта (пример)
echo "Скрипт запущен от root. Продолжаем выполнение..."
